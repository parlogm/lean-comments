struct Baseline {
    tree: String,
    head: String,
    time: u64,
    top: PathBuf,
}

impl Baseline {
    fn load(state: &Path, name: &str) -> Option<Baseline> {
        let text = fs::read_to_string(state.join(name)).ok()?;
        let mut lines = text.lines();
        let tree = lines.next()?.to_string();
        let head = lines.next()?.to_string();
        let time = lines.next()?.parse().ok()?;
        let top = PathBuf::from(lines.next()?);
        (!tree.is_empty()).then_some(Baseline { tree, head, time, top })
    }

    fn save(&self, state: &Path, name: &str) {
        let body = format!("{}\n{}\n{}\n{}\n", self.tree, self.head, self.time, self.top.to_string_lossy());
        let tmp = state.join(format!("{name}.tmp"));
        if fs::write(&tmp, body).is_ok() {
            let _ = fs::rename(&tmp, state.join(name));
        }
    }
}

fn null_separated(bytes: &[u8]) -> impl Iterator<Item = &[u8]> {
    bytes.split(|b| *b == 0).filter(|p| !p.is_empty())
}

// The snapshot goes through a private copy of the index, so the user's index and history are never touched.
fn snapshot(top: &Path, state: &Path) -> Option<Baseline> {
    let index = state.join("index");
    let real_index = first_line(&git(top, None, &["rev-parse", "--git-path", "index"], None)?);
    let _ = fs::remove_file(&index);
    if fs::copy(top.join(real_index), &index).is_err() {
        let _ = fs::remove_file(&index);
    }
    let listed = git(top, Some(&index), &["ls-files", "-z", "-m", "-d", "-o", "--exclude-standard"], None)?;
    let mut paths: Vec<&[u8]> = null_separated(&listed)
        .filter(|p| lang_for(&String::from_utf8_lossy(p)).is_some())
        .filter(|p| {
            let size = fs::metadata(top.join(String::from_utf8_lossy(p).as_ref())).map(|m| m.len());
            size.map_or(true, |len| len <= MAX_SNAPSHOT_FILE_BYTES)
        })
        .collect();
    paths.sort_unstable();
    paths.dedup();
    // Unmerged entries the snapshot does not stage would make write-tree fail during a merge or rebase.
    let unmerged = git(top, Some(&index), &["ls-files", "-z", "-u"], None)?;
    let mut dropped: Vec<&[u8]> = null_separated(&unmerged)
        .filter_map(|entry| entry.iter().position(|b| *b == b'\t').map(|tab| &entry[tab + 1..]))
        .filter(|path| paths.binary_search(path).is_err())
        .collect();
    dropped.sort_unstable();
    dropped.dedup();
    for (list, mode) in [(&dropped, "--force-remove"), (&paths, "--add")] {
        if !list.is_empty() {
            let mut input = list.join(&0u8);
            input.push(0);
            git(top, Some(&index), &["update-index", "-z", mode, "--remove", "--stdin"], Some(&input))?;
        }
    }
    let tree = first_line(&git(top, Some(&index), &["write-tree"], None)?);
    let head = git(top, None, &["rev-parse", "-q", "--verify", "HEAD"], None).map_or(String::new(), |o| first_line(&o));
    Some(Baseline { tree, head, time: unix_now(), top: top.to_path_buf() })
}

// A moved HEAD counts as the agent's own work only if every commit it gained is fresh and not a merge.
fn head_moved_by_new_commits(before: &Baseline, head: &str) -> bool {
    if head.is_empty() {
        return false;
    }
    let limit = format!("--max-count={}", MAX_TURN_COMMITS + 1);
    let exclude = format!("^{}", before.head);
    let mut args = vec!["rev-list", "--timestamp", "--parents", &limit, head];
    if !before.head.is_empty() {
        args.push(&exclude);
    }
    let Some(listed) = git(&before.top, None, &args, None) else { return false };
    let listed = String::from_utf8_lossy(&listed);
    let commits: Vec<Vec<&str>> = listed.lines().map(|l| l.split_whitespace().collect()).collect();
    !commits.is_empty()
        && commits.len() <= MAX_TURN_COMMITS
        && commits.iter().all(|parts| {
            let fresh = parts.first().and_then(|t| t.parse::<u64>().ok()).is_some_and(|t| t >= before.time);
            fresh && parts.len() <= 3
        })
}

fn is_generated(path: &Path) -> bool {
    let mut head = Vec::new();
    let read = fs::File::open(path).and_then(|f| f.take(4096).read_to_end(&mut head));
    read.is_ok() && GENERATED.is_match(&String::from_utf8_lossy(&head))
}

fn load_checked(state: &Path) -> HashMap<String, String> {
    let mut checked: HashMap<String, String> = HashMap::new();
    let text = fs::read_to_string(state.join("checked")).unwrap_or_default();
    for record in text.lines().filter_map(|line| serde_json::from_str::<Value>(line).ok()) {
        if let (Some(path), Some(text)) = (record["path"].as_str(), record["text"].as_str()) {
            let seen = checked.entry(path.to_string()).or_default();
            seen.push_str("\n\n");
            seen.push_str(text);
        }
    }
    checked
}

fn turn_sections(before: &Baseline, after: &Baseline, checked: &HashMap<String, String>) -> Option<Vec<String>> {
    let specs: Vec<String> =
        C_STYLE.iter().chain(HASH).chain(&["sql"]).map(|ext| format!(":(icase)*.{ext}")).collect();
    let mut args = vec![
        "diff", "--no-color", "--no-ext-diff", "--no-textconv", "-M", "--src-prefix=a/", "--dst-prefix=b/", "-U3",
        &before.tree, &after.tree, "--",
    ];
    args.extend(specs.iter().map(String::as_str));
    let diff = git(&before.top, None, &args, None)?;
    let mut unrecorded = 0;
    let files: Vec<(String, Pairs)> = parse_unified_diff(&String::from_utf8_lossy(&diff))
        .into_iter()
        .filter_map(|(path, pairs)| {
            let full = before.top.join(&path);
            if is_generated(&full) {
                return None;
            }
            let seen = fs::canonicalize(&full).ok().and_then(|real| checked.get(real.to_string_lossy().as_ref()));
            let Some(seen) = seen else {
                unrecorded += 1;
                return Some((path, pairs));
            };
            // Text the edit hook already judged counts as pre-existing, so only script-made additions are new.
            Some((path, pairs.into_iter().map(|(old, new)| (format!("{old}\n\n{seen}"), new)).collect()))
        })
        .collect();
    (unrecorded <= MAX_TURN_FILES).then(|| report(&files, ""))
}

fn is_off() -> bool {
    ["LEAN_COMMENTS", "CLAUDE_LEAN_COMMENTS"]
        .iter()
        .any(|name| env::var_os(name).is_some_and(|v| v.to_string_lossy().to_lowercase() == "off"))
}

fn is_copilot() -> bool {
    env::var_os("COPILOT_CLI").is_some_and(|v| !v.is_empty())
}

fn emit(value: &Value) {
    let _ = writeln!(std::io::stdout(), "{value}");
}

fn session_start() {
    if is_off() {
        return;
    }
    if is_copilot() {
        emit(&json!({"additionalContext": RULE}));
    } else {
        emit(&json!({"hookSpecificOutput": {"hookEventName": "SessionStart", "additionalContext": RULE}}));
    }
}

fn record_checked_files(event: &Value, files: &[(String, Pairs)]) {
    let Some(state) = state_dir(event).filter(|dir| dir.is_dir()) else { return };
    let cwd = Path::new(event_cwd(event));
    let mut records = String::new();
    for (path, pairs) in files {
        let Ok(real) = fs::canonicalize(cwd.join(path)) else { continue };
        let text = pairs.iter().map(|(_, new)| new.as_str()).collect::<Vec<_>>().join("\n\n");
        if text.len() as u64 <= MAX_SNAPSHOT_FILE_BYTES {
            records.push_str(&json!({"path": real.to_string_lossy(), "text": text}).to_string());
            records.push('\n');
        }
    }
    if records.is_empty() {
        return;
    }
    if let Ok(mut file) = fs::OpenOptions::new().create(true).append(true).open(state.join("checked")) {
        let _ = file.write_all(records.as_bytes());
    }
}

fn post_tool_use() {
    if is_off() {
        return;
    }
    let Some(event) = read_event() else { return };
    let Ok(files) = edits_by_file(&event) else { return };
    record_checked_files(&event, &files);
    let sections = report(&files, event_cwd(&event));
    if sections.is_empty() {
        return;
    }
    let reason = format!("{}\n{ADVICE}", sections.join("\n"));
    // Copilot documents only additionalContext for feeding postToolUse output to the model.
    if is_copilot() {
        emit(&json!({"additionalContext": reason}));
    } else {
        emit(&json!({"decision": "block", "reason": reason}));
    }
}

fn user_prompt_submit() {
    if is_off() {
        return;
    }
    let Some(event) = read_event() else { return };
    let Some(state) = state_dir(&event) else { return };
    if ensure_private_dir(&state).is_none() {
        return;
    }
    // Mark the turn as started before any git call, so a Stop that races this background hook waits or stays silent.
    let pending = state.join("pending");
    let marked = fs::write(&pending, b"").is_ok();
    for name in ["baseline", "continuation", "blocked", "checked"] {
        let _ = fs::remove_file(state.join(name));
    }
    if !marked {
        return;
    }
    prune_old_states(&state);
    let cwd = event_cwd(&event);
    let top = (!cwd.is_empty()).then(|| git(Path::new(cwd), None, &["rev-parse", "--show-toplevel"], None)).flatten();
    if let Some(baseline) = top.and_then(|out| snapshot(&PathBuf::from(first_line(&out)), &state)) {
        baseline.save(&state, "baseline");
    }
    let _ = fs::remove_file(pending);
}

fn snapshot_ready(state: &Path) -> bool {
    let pending = state.join("pending");
    let started = Instant::now();
    while let Ok(meta) = fs::metadata(&pending) {
        let abandoned = meta.modified().ok().and_then(|t| t.elapsed().ok()).is_some_and(|age| age > SNAPSHOT_ABANDONED);
        if abandoned || started.elapsed() > SNAPSHOT_WAIT {
            return false;
        }
        std::thread::sleep(Duration::from_millis(100));
    }
    true
}

// Only a prompt arms the check; the turn-end snapshot is kept just for a continuation some Stop hook forces.
fn stop() {
    if is_off() {
        return;
    }
    let Some(event) = read_event() else { return };
    let Some(state) = state_dir(&event) else { return };
    if !snapshot_ready(&state) {
        return;
    }
    let continued = truthy(event.get("stop_hook_active").unwrap_or(&Value::Null));
    let before = Baseline::load(&state, if continued { "continuation" } else { "baseline" });
    let blocked_by_us = continued && state.join("blocked").exists();
    let checked = load_checked(&state);
    for name in ["baseline", "continuation", "blocked", "checked"] {
        let _ = fs::remove_file(state.join(name));
    }
    let Some(before) = before else { return };
    let Some(after) = snapshot(&before.top, &state) else { return };
    after.save(&state, "continuation");
    if blocked_by_us || before.tree == after.tree {
        return;
    }
    if before.head != after.head && !head_moved_by_new_commits(&before, &after.head) {
        return;
    }
    let Some(sections) = turn_sections(&before, &after, &checked) else { return };
    if sections.is_empty() {
        return;
    }
    let _ = fs::write(state.join("blocked"), b"");
    let reason = format!("{TURN_INTRO}\n{}\n{ADVICE} {TURN_ADVICE}", sections.join("\n"));
    emit(&json!({"decision": "block", "reason": reason}));
}

fn main() {
    let command = env::args().nth(1).unwrap_or_default();
    std::panic::set_hook(Box::new(|_| {}));
    // A linting bug must never fail the agent's edit, so panics end the hook quietly.
    let _ = std::panic::catch_unwind(|| match command.as_str() {
        "session-start" => session_start(),
        "post-tool-use" => post_tool_use(),
        "user-prompt-submit" => user_prompt_submit(),
        "stop" => stop(),
        other => {
            eprintln!(
                "lean-comments: unknown command '{other}', expected session-start, post-tool-use, user-prompt-submit or stop"
            );
            std::process::exit(1);
        }
    });
}
